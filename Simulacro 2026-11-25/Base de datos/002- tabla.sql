CREATE TABLE videojuegos(
	id INT PRIMARY KEY AUTO_INCREMENT,
  titulo VARCHAR(100),
  desarrollador VARCHAR(100),
  distribuidor VARCHAR(100),
  genero VARCHAR(100),
  descripcion TEXT,
  anio_lanzamiento INT,
  fecha_lanzamiento DATE,
  plataforma VARCHAR(100),
  pais VARCHAR(100),
  idioma VARCHAR(100),
  clasificacion_edades INT,
  presupuesto DECIMAL,
  ingresos DECIMAL,
  valoracion_media DECIMAL,
  numero_valoraciones INT,
  unidades_vendidas INT,
  disponible INT,
  multijugador INT,
  favorito INT,
  imagen_portada VARCHAR(100),
  url_trailer VARCHAR(100),
  precio_original DECIMAL,
  precio_rebajado DECIMAL,
  espacio_requerido DECIMAL,
  compras_integradas INT
 
);
