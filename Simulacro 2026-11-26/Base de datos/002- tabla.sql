CREATE TABLE vehiculos(
	id INT PRIMARY KEY AUTO_INCREMENT,
  marca VARCHAR(100),
  modelo VARCHAR(100),
  version VARCHAR(100),
  categoria VARCHAR(100),
  descripcion TEXT,
  anio_fabricacion INT,
  fecha_matriculacion DATE,
  matricula VARCHAR(100),
  pais VARCHAR(100),
  color VARCHAR(100),
  combustible VARCHAR(100),
  potencia INT,
  cilindrada INT,
  kilometraje INT,
  numero_puertas INT,
  numero_plazas INT,
  consumo_medio DECIMAL,
  automatico INT,
  disponible INT,
  segunda_mano INT,
  imagen VARCHAR(100), 
  url_fabricante VARCHAR(100),
  precio_original DECIMAL,
  precio_venta DECIMAL,
  garantia_vigente INT
 
);
